function openStoryModal(storyId) {
  const story = klStoriesData[storyId];
  if (!story) return;

  const modalOverlay = document.getElementById('klStoryModal');
  const modalHeroImg = document.getElementById('modalHeroImg');
  const modalTag = document.getElementById('modalTag');
  const modalTitle = document.getElementById('modalTitle');
  const modalSubtitle = document.getElementById('modalSubtitle');
  const modalQuote = document.getElementById('modalQuote');
  const modalBody = document.getElementById('modalBody');
  const modalTipsList = document.getElementById('modalTipsList');
  const modalGalleryWrap = document.getElementById('modalGalleryWrap');
  const modalMapLink = document.getElementById('modalMapLink');

  if (modalHeroImg) {
    modalHeroImg.src = story.heroImg;
    modalHeroImg.alt = story.title;
    modalHeroImg.style.objectPosition = story.heroImgPosition || 'center center';
  }
  if (modalTag) modalTag.textContent = story.tag;
  if (modalTitle) modalTitle.textContent = story.title;
  if (modalSubtitle) modalSubtitle.textContent = story.subtitle;
  if (modalQuote) modalQuote.textContent = story.quote;

  if (modalGalleryWrap && story.gallery) {
    modalGalleryWrap.innerHTML = story.gallery.map((item, idx) => `
      <figure class="modal-gallery-card">
        <div class="gallery-card-thumb">
          <img src="${item.img}" alt="${item.title}" loading="lazy">
          <span class="gallery-card-pill">Foto ${idx + 1}</span>
        </div>
        <figcaption class="gallery-card-caption">
          <strong>${item.title}</strong>
          <p>${item.caption}</p>
        </figcaption>
      </figure>
    `).join('');
  }

  if (modalBody) {
    modalBody.innerHTML = story.narrative.map((p, index) => {

      const className = index === 0 ? 'storybook-dropcap' : 'storybook-p';
      return `<p class="${className}">${p}</p>`;
    }).join('');
  }

  if (modalMapLink && story.mapUrl) {
    modalMapLink.href = story.mapUrl;
    modalMapLink.innerHTML = `
      <svg width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round">
        <path d="M21 10c0 7-9 13-9 13s-9-6-9-13a9 9 0 0 1 18 0z"></path>
        <circle cx="12" cy="10" r="3"></circle>
      </svg>
      <span>${story.mapLabel}</span>
    `;
  }

  if (modalTipsList && story.tips) {
    modalTipsList.innerHTML = story.tips.map(t => `<li>${t}</li>`).join('');
  }

  const modalContainer = document.querySelector('.kl-modal-container');
  if (modalContainer) {
    modalContainer.scrollTop = 0;
  }
  const finishBtn = document.querySelector('.kl-modal-finish-btn');
  if (finishBtn) {
    finishBtn.classList.remove('is-completed');
    finishBtn.innerHTML = `
      <span class="btn-icon">🏆</span>
      <span class="btn-label">Selesai Membaca Bab &amp; Buka Penghargaan</span>
      <span class="btn-sparkle">✨</span>
    `;
    finishBtn.disabled = false;
  }

  modalOverlay.classList.add('active');
  document.body.style.overflow = 'hidden';
}

function closeStoryModal() {
  const modalOverlay = document.getElementById('klStoryModal');
  if (modalOverlay) {
    modalOverlay.classList.remove('active');
    document.body.style.overflow = '';
  }
}

function launchReadingAwardConfetti() {
  if (typeof initConfetti === 'function') {
    initConfetti();
  }

  const colors = [
    '#FF6636',
    '#FFC857',
    '#14634A',
    '#3B82F6',
    '#EC4899',
    '#10B981',
    '#F59E0B',
    '#FFFFFF'
  ];

  if (typeof confettiParticles === 'undefined') {
    window.confettiParticles = [];
  }

  const cannonOrigins = [
    { x: window.innerWidth * 0.15, y: window.innerHeight * 0.85, count: 55, angleSpread: [-75, -30] },
    { x: window.innerWidth * 0.50, y: window.innerHeight * 0.60, count: 75, angleSpread: [-130, -50] },
    { x: window.innerWidth * 0.85, y: window.innerHeight * 0.85, count: 55, angleSpread: [-150, -105] }
  ];

  cannonOrigins.forEach(origin => {
    for (let i = 0; i < origin.count; i++) {
      const angleDeg = origin.angleSpread[0] + Math.random() * (origin.angleSpread[1] - origin.angleSpread[0]);
      const angleRad = (angleDeg * Math.PI) / 180;
      const speed = Math.random() * 16 + 9;

      confettiParticles.push({
        x: origin.x,
        y: origin.y,
        vx: Math.cos(angleRad) * speed,
        vy: Math.sin(angleRad) * speed,
        color: colors[Math.floor(Math.random() * colors.length)],
        radius: Math.random() * 7 + 4,
        rotation: Math.random() * 360,
        vRot: (Math.random() - 0.5) * 14,
        life: 140
      });
    }
  });

  if (typeof triggerConfetti === 'function') {
    triggerConfetti();
  }
}

function showAwardToast() {
  let toast = document.getElementById('sakalaAwardToast');
  if (!toast) {
    toast = document.createElement('div');
    toast.id = 'sakalaAwardToast';
    toast.className = 'sakala-award-toast';
    document.body.appendChild(toast);
  }

  toast.innerHTML = `
    <div class="award-toast-trophy">🏆</div>
    <div class="award-toast-body">
      <span class="award-toast-badge">PENGHARGAAN PEMBACA BUDAYA</span>
      <h4 class="award-toast-title">Bab Selesai Dibaca! ✨</h4>
      <p class="award-toast-text">Kearifan hidup &amp; harmoni krama Bali kini memperkaya wawasan Anda.</p>
    </div>
    <button type="button" class="award-toast-close" onclick="dismissAwardToast()" aria-label="Tutup Notifikasi">&times;</button>
  `;

  requestAnimationFrame(() => {
    toast.classList.add('show');
  });

  if (window.awardToastTimeout) clearTimeout(window.awardToastTimeout);
  window.awardToastTimeout = setTimeout(() => {
    dismissAwardToast();
  }, 5000);
}

function dismissAwardToast() {
  const toast = document.getElementById('sakalaAwardToast');
  if (toast) {
    toast.classList.remove('show');
  }
}

function finishStoryChapter() {
  const finishBtn = document.querySelector('.kl-modal-finish-btn');

  launchReadingAwardConfetti();

  setTimeout(() => {
    launchReadingAwardConfetti();
  }, 300);

  if (finishBtn) {
    finishBtn.classList.add('is-completed');
    finishBtn.innerHTML = `
      <span class="btn-icon">🎉</span>
      <span class="btn-label">Selamat! Bab Telah Selesai Dibaca</span>
      <span class="btn-sparkle">✨</span>
    `;
    finishBtn.disabled = true;
  }

  showAwardToast();

  setTimeout(() => {
    closeStoryModal();
  }, 2400);
}

let isKlSliding = false;
let klActiveStoryIndex = 0;

function updateKlStoryStatus(activeIndex) {
  klActiveStoryIndex = activeIndex;
  const dots = document.querySelectorAll('.kl-dot');
  dots.forEach((dot, idx) => {
    dot.classList.toggle('active', idx === activeIndex);
  });
  const counterSpan = document.getElementById('klActiveStoryNum');
  if (counterSpan) {
    counterSpan.textContent = activeIndex + 1;
  }
}

