let currentCoverflowIndex = 2;

function updateCoverflowPositions() {
  const stage = document.getElementById('klCoverflowStage');
  const cards = document.querySelectorAll('.kl-coverflow-card');
  if (!stage || !cards.length) return;

  const width = window.innerWidth;
  const isMobile = width < 480;
  const isTablet = width >= 480 && width < 768;

  const xSpacing = isMobile ? 80 : (isTablet ? 130 : 180);
  const zOffset = isMobile ? -35 : -55;
  const rotateAngle = isMobile ? 24 : 32;

  cards.forEach((card, i) => {
    let offset = i - currentCoverflowIndex;

    if (offset > 2) offset -= 5;
    if (offset < -2) offset += 5;

    card.setAttribute('data-offset', offset);

    if (offset === 0) {

      card.style.transform = `translate3d(0, 0, 50px) rotateY(0deg) scale(1.15)`;
      card.style.zIndex = '10';
      card.style.opacity = '1';
      card.style.filter = 'brightness(1)';
      card.style.boxShadow = '0 24px 60px rgba(0, 0, 0, 0.28), 0 4px 16px rgba(0, 0, 0, 0.1)';
      card.style.pointerEvents = 'auto';
      card.classList.add('is-active');
    } else if (Math.abs(offset) === 1) {

      const dir = offset > 0 ? 1 : -1;
      card.style.transform = `translate3d(${dir * xSpacing}px, 0, ${zOffset}px) rotateY(${-dir * rotateAngle}deg) scale(0.92)`;
      card.style.zIndex = '5';
      card.style.opacity = '0.88';
      card.style.filter = 'brightness(0.92)';
      card.style.boxShadow = '0 14px 32px rgba(0, 0, 0, 0.16)';
      card.style.pointerEvents = 'auto';
      card.classList.remove('is-active');
    } else if (Math.abs(offset) === 2) {

      const dir = offset > 0 ? 1 : -1;
      card.style.transform = `translate3d(${dir * xSpacing * 1.8}px, 0, ${zOffset * 2}px) rotateY(${-dir * (rotateAngle + 12)}deg) scale(0.80)`;
      card.style.zIndex = '2';
      card.style.opacity = '0.62';
      card.style.filter = 'brightness(0.85)';
      card.style.boxShadow = '0 10px 24px rgba(0, 0, 0, 0.12)';
      card.style.pointerEvents = 'auto';
      card.classList.remove('is-active');
    } else {

      card.style.transform = `translate3d(${offset > 0 ? 400 : -400}px, 0, -200px) scale(0.6)`;
      card.style.zIndex = '0';
      card.style.opacity = '0';
      card.style.pointerEvents = 'none';
      card.classList.remove('is-active');
    }
  });

  const activeData = klCoverflowData[currentCoverflowIndex];
  if (activeData) {
    const stepNumEl = document.getElementById('klCoverflowStepNum');
    const titleEl = document.getElementById('klCoverflowTitle');
    const descEl = document.getElementById('klCoverflowDesc');
    const infoWrap = document.getElementById('klCoverflowInfo');

    if (infoWrap) {
      infoWrap.style.opacity = '0.4';
      infoWrap.style.transform = 'translateY(4px)';
      setTimeout(() => {
        if (stepNumEl) stepNumEl.textContent = activeData.stepNum;
        if (titleEl) titleEl.textContent = activeData.title;
        if (descEl) descEl.textContent = activeData.desc;
        infoWrap.style.opacity = '1';
        infoWrap.style.transform = 'translateY(0)';
      }, 150);
    }
  }
}

function selectCoverflowStep(index) {
  if (index === currentCoverflowIndex) return;
  currentCoverflowIndex = index;
  updateCoverflowPositions();
}

function stepCoverflow(direction) {
  currentCoverflowIndex = (currentCoverflowIndex + direction + 5) % 5;
  updateCoverflowPositions();
}

function initCoverflow() {
  const stage = document.getElementById('klCoverflowStage');
  if (!stage) return;

  updateCoverflowPositions();

  let startX = 0, startY = 0, distX = 0, distY = 0;

  stage.addEventListener('touchstart', (e) => {
    startX = e.touches[0].clientX;
    startY = e.touches[0].clientY;
    distX = 0;
    distY = 0;
  }, { passive: true });

  stage.addEventListener('touchmove', (e) => {
    distX = e.touches[0].clientX - startX;
    distY = e.touches[0].clientY - startY;
  }, { passive: true });

  stage.addEventListener('touchend', () => {
    if (Math.abs(distX) > 40 && Math.abs(distX) > Math.abs(distY)) {
      if (distX < 0) {
        stepCoverflow(1);
      } else {
        stepCoverflow(-1);
      }
    }
  }, { passive: true });

  let isDragging = false;
  let mouseStartX = 0;
  let mouseDistX = 0;

  stage.addEventListener('mousedown', (e) => {
    isDragging = true;
    mouseStartX = e.clientX;
    mouseDistX = 0;
  });

  window.addEventListener('mousemove', (e) => {
    if (!isDragging) return;
    mouseDistX = e.clientX - mouseStartX;
  });

  window.addEventListener('mouseup', () => {
    if (!isDragging) return;
    isDragging = false;
    if (Math.abs(mouseDistX) > 40) {
      if (mouseDistX < 0) {
        stepCoverflow(1);
      } else {
        stepCoverflow(-1);
      }
    }
  });

  stage.addEventListener('keydown', (e) => {
    if (e.key === 'ArrowLeft') {
      stepCoverflow(-1);
    } else if (e.key === 'ArrowRight') {
      stepCoverflow(1);
    }
  });

  window.addEventListener('resize', () => {
    updateCoverflowPositions();
  });
}

