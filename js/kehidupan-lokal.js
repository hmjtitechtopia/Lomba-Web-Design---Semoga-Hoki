function goToKlStory(targetIndex) {
  const track = document.getElementById('klCarouselTrack');
  if (!track || isKlSliding) return;

  const currentFirst = track.firstElementChild;
  if (!currentFirst) return;

  const currentIndex = parseInt(currentFirst.dataset.storyIndex, 10);
  if (currentIndex === targetIndex) return;

  let diff = targetIndex - currentIndex;
  if (diff < -2) diff += 5;
  if (diff > 2) diff -= 5;

  if (diff > 0) {
    slideKlStory(1);
    if (diff > 1) {
      setTimeout(() => goToKlStory(targetIndex), 450);
    }
  } else if (diff < 0) {
    slideKlStory(-1);
    if (diff < -1) {
      setTimeout(() => goToKlStory(targetIndex), 450);
    }
  }
}

